#!/usr/bin/env python3
"""Build Lumora's macOS app icon.

    scripts/make_icon.py            # writes packaging/icon/AppIcon.svg and packaging/AppIcon.icns

1. Generates ``packaging/icon/AppIcon.svg``: a Big Sur-style squircle with an
   indigo → violet gradient (DESIGN.md › App icon), the viewfinder brackets of
   the Lumora mark and a six-blade aperture "lens" glowing at the centre.
2. Rasterises it at every size an .icns needs (cairosvg, falling back to
   rsvg-convert or ImageMagick).
3. Writes ``packaging/AppIcon.icns`` directly (PNG-in-ICNS, the format
   ``iconutil`` produces), so no macOS tools are needed. On a Mac,
   ``scripts/bundle.sh`` can instead regenerate it with ``iconutil`` from
   the same PNGs (ICONUTIL=1).
"""

import io
import math
import os
import shutil
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG_PATH = os.path.join(ROOT, "packaging", "icon", "AppIcon.svg")
ICNS_PATH = os.path.join(ROOT, "packaging", "AppIcon.icns")

# Indigo → violet, the dark-mode system indigo/purple (DESIGN.md).
INDIGO = "#5E5CE6"
MID = "#7B5CF0"
VIOLET = "#BF5AF2"


def squircle(cx, cy, half, n=5.0, steps=256):
    """Superellipse |x|^n + |y|^n = r^n — the continuous-corner icon shape."""
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        x = half * math.copysign(abs(c) ** (2 / n), c)
        y = half * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f"{cx + x:.2f},{cy + y:.2f}")
    return "M" + " L".join(pts) + " Z"


def blades(cx, cy, r, count=6):
    """Aperture blades: each a curved wedge from the rim toward an inner hexagon."""
    paths = []
    inner = r * 0.42
    for i in range(count):
        a0 = 2 * math.pi * i / count - math.pi / 2
        a1 = a0 + 2 * math.pi / count
        p0 = (cx + r * math.cos(a0), cy + r * math.sin(a0))
        p1 = (cx + r * math.cos(a1), cy + r * math.sin(a1))
        q = (cx + inner * math.cos(a1 + 0.55), cy + inner * math.sin(a1 + 0.55))
        paths.append(
            f'<path d="M{p0[0]:.1f},{p0[1]:.1f} A{r:.1f},{r:.1f} 0 0 1 {p1[0]:.1f},{p1[1]:.1f} '
            f'L{q[0]:.1f},{q[1]:.1f} Z" fill="url(#blade)" stroke="#FFFFFF" stroke-opacity="0.35" '
            f'stroke-width="3" stroke-linejoin="round"/>'
        )
    return "\n    ".join(paths)


def brackets(c, span, arm, width):
    lo, hi = c - span, c + span
    corners = [
        (lo, lo + arm, lo, lo, lo + arm, lo),
        (hi - arm, lo, hi, lo, hi, lo + arm),
        (hi, hi - arm, hi, hi, hi - arm, hi),
        (lo + arm, hi, lo, hi, lo, hi - arm),
    ]
    return "\n    ".join(
        f'<path d="M{a},{b} L{x},{y} L{e},{f}" fill="none" stroke="#FFFFFF" stroke-width="{width}" '
        f'stroke-linecap="round" stroke-linejoin="round"/>'
        for a, b, x, y, e, f in corners
    )


def build_svg():
    size, c = 1024, 512
    body = squircle(c, c, 412)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Lumora app icon. Generated by scripts/make_icon.py — edit the script, not this file. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">
  <defs>
    <linearGradient id="bg" x1="0.1" y1="0" x2="0.9" y2="1">
      <stop offset="0" stop-color="{INDIGO}"/>
      <stop offset="0.55" stop-color="{MID}"/>
      <stop offset="1" stop-color="{VIOLET}"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.55"/>
      <stop offset="0.45" stop-color="#E9E3FF" stop-opacity="0.18"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="lens" cx="0.42" cy="0.38" r="0.7">
      <stop offset="0" stop-color="#FFFFFF"/>
      <stop offset="0.6" stop-color="#ECE6FF"/>
      <stop offset="1" stop-color="#C9BBFF"/>
    </radialGradient>
    <linearGradient id="blade" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{INDIGO}" stop-opacity="0.95"/>
      <stop offset="1" stop-color="{VIOLET}" stop-opacity="0.85"/>
    </linearGradient>
    <linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.22"/>
      <stop offset="0.5" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
    <filter id="drop" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="14"/>
      <feOffset dy="12"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.32"/></feComponentTransfer>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <clipPath id="shape"><path d="{body}"/></clipPath>
  </defs>
  <g filter="url(#drop)">
    <path d="{body}" fill="url(#bg)"/>
  </g>
  <g clip-path="url(#shape)">
    <circle cx="{c}" cy="{c}" r="330" fill="url(#glow)"/>
    <rect x="0" y="0" width="{size}" height="{size}" fill="url(#sheen)"/>
    {brackets(c, 250, 104, 46)}
    <circle cx="{c}" cy="{c}" r="138" fill="url(#lens)"/>
    {blades(c, c, 112)}
    <circle cx="{c}" cy="{c}" r="34" fill="#FFFFFF"/>
    <circle cx="{c - 52}" cy="{c - 58}" r="16" fill="#FFFFFF" fill-opacity="0.85"/>
  </g>
  <path d="{body}" fill="none" stroke="#FFFFFF" stroke-opacity="0.18" stroke-width="3"/>
</svg>
"""


def rasterize(svg_bytes, px):
    try:
        import cairosvg  # type: ignore

        return cairosvg.svg2png(bytestring=svg_bytes, output_width=px, output_height=px)
    except ImportError:
        pass
    with tempfile.TemporaryDirectory() as d:
        src, dst = os.path.join(d, "i.svg"), os.path.join(d, "i.png")
        with open(src, "wb") as f:
            f.write(svg_bytes)
        if shutil.which("rsvg-convert"):
            subprocess.check_call(["rsvg-convert", "-w", str(px), "-h", str(px), src, "-o", dst])
        elif shutil.which("magick") or shutil.which("convert"):
            tool = shutil.which("magick") or shutil.which("convert")
            subprocess.check_call([tool, "-background", "none", "-density", "384", src, "-resize", f"{px}x{px}", dst])
        else:
            sys.exit("need cairosvg, rsvg-convert or ImageMagick to rasterise the icon")
        with open(dst, "rb") as f:
            return f.read()


# (ICNS type, pixel size, iconset file name)
ENTRIES = [
    (b"icp4", 16, "icon_16x16.png"),
    (b"ic11", 32, "icon_16x16@2x.png"),
    (b"icp5", 32, "icon_32x32.png"),
    (b"ic12", 64, "icon_32x32@2x.png"),
    (b"ic07", 128, "icon_128x128.png"),
    (b"ic13", 256, "icon_128x128@2x.png"),
    (b"ic08", 256, "icon_256x256.png"),
    (b"ic14", 512, "icon_256x256@2x.png"),
    (b"ic09", 512, "icon_512x512.png"),
    (b"ic10", 1024, "icon_512x512@2x.png"),
]


def write_icns(pngs, path):
    """ICNS = 'icns' + total length, then (type, length incl. 8-byte header, PNG)."""
    chunks = b"".join(t + struct.pack(">I", len(data) + 8) + data for t, data in pngs)
    with open(path, "wb") as f:
        f.write(b"icns" + struct.pack(">I", len(chunks) + 8) + chunks)


def read_icns(path):
    """Parse back (for the self-check)."""
    with open(path, "rb") as f:
        blob = f.read()
    assert blob[:4] == b"icns" and struct.unpack(">I", blob[4:8])[0] == len(blob)
    out, i = [], 8
    while i < len(blob):
        t, n = blob[i : i + 4], struct.unpack(">I", blob[i + 4 : i + 8])[0]
        out.append((t, blob[i + 8 : i + n]))
        i += n
    return out


def main():
    iconset = None
    if len(sys.argv) > 2 and sys.argv[1] == "--iconset":
        iconset = sys.argv[2]
    svg = build_svg()
    os.makedirs(os.path.dirname(SVG_PATH), exist_ok=True)
    with open(SVG_PATH, "w") as f:
        f.write(svg)
    cache = {}
    pngs = []
    for t, px, name in ENTRIES:
        if px not in cache:
            cache[px] = rasterize(svg.encode(), px)
        pngs.append((t, cache[px]))
        if iconset:
            os.makedirs(iconset, exist_ok=True)
            with open(os.path.join(iconset, name), "wb") as f:
                f.write(cache[px])
    write_icns(pngs, ICNS_PATH)
    parsed = read_icns(ICNS_PATH)
    assert [t for t, _ in parsed] == [t for t, _, _ in ENTRIES]
    assert all(d[:8] == b"\x89PNG\r\n\x1a\n" for _, d in parsed)
    print(f"wrote {os.path.relpath(SVG_PATH, ROOT)} and {os.path.relpath(ICNS_PATH, ROOT)} "
          f"({os.path.getsize(ICNS_PATH) // 1024} KB, {len(parsed)} images)")


if __name__ == "__main__":
    main()
